CREATE DATABASE BIBLIOTECA_CONECTADA_JONAS

USE BIBLIOTECA_CONECTADA_JONAS


CREATE TABLE USUARIO(
ID_USUARIO INT AUTO_INCREMENT PRIMARY KEY,
    NOME VARCHAR (100) NOT NULL,
    EMAIL VARCHAR(120) NOT NULL, 
    TELEFONE VARCHAR (60) NOT NULL,
    ATIVO BOOLEAN DEFAULT TRUE
    ); 

CREATE TABLE LIVRO (
    ID_LIVRO INT AUTO_INCREMENT PRIMARY KEY,
    TITULO VARCHAR(150) NOT NULL,
    AUTOR VARCHAR(120) NOT NULL,
    ISBN CHAR(13) NOT NULL UNIQUE,
    ANO_PUBLICACAO INT,
    QUANTIDADE_DISPONIVEL INT 
);

CREATE TABLE EMPRESTIMO(
    ID_EMPRESTIMO INT AUTO_INCREMENT PRIMARY KEY,
    DATA_EMPRESTIMO DATETIME DEFAULT CURRENT_TIMESTAMP,
    DATA_PREVISTA DATE NOT NULL,
    DATA_DEVOLUCAO DATE,
    STATUS_EMPRESTIMO VARCHAR(20) DEFAULT'ABERTO' CHECK
    ID_USUARIO INT  Foreign Key (USUARIO) REFERENCES (USUARIO)
    ID_LIVRO INT Foreign Key (LIVRO) REFERENCES (LIVRO)

); 

CREATE TABLE ATRASO(
    ID_ATRASO INT AUTO_INCREMENT PRIMARY KEY,
    DATA_ATRASO DATE NOT NULL,
    STATUS_ATRASO VARCHAR(20),
    MULTA_ATRASO INT
);

CREATE TABLE COMPRA(
    ID_COMPRA INT AUTO_INCREMENT PRIMARY KEY,
    DATA_COMPRA DATE NOT NULL,
    STATUS_COMPRA VARCHAR (20)
);

